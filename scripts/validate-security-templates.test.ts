#!/usr/bin/env bun

import { describe, expect, test } from "bun:test";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";

const TEMPLATE_DIR = join(import.meta.dir, "..", ".agent-sync", "skills", "conventions-init", "references", "templates");

function readTemplate(name: string): string {
  return readFileSync(join(TEMPLATE_DIR, name), "utf-8");
}

describe("security workflow templates", () => {
  test("security templates are parseable generated GitHub Actions workflows", () => {
    const templates = readdirSync(TEMPLATE_DIR).filter((name) => name.startsWith("security") && name.endsWith(".yml"));

    expect(templates).toContain("security.yml");
    expect(templates).toContain("security-baseline.yml");
    expect(templates).toContain("security-production-js-ts.yml");
    expect(templates).toContain("security-production-web-js-ts.yml");

    for (const template of templates) {
      const content = readTemplate(template);
      const workflow = parse(content);

      expect(content).toContain("# @generated by conventions-init");
      expect(typeof workflow.name).toBe("string");
      expect(typeof workflow.jobs).toBe("object");
      expect(content).not.toMatch(/sk-[A-Za-z0-9]/);
      expect(content).not.toMatch(/BEGIN (RSA |EC |OPENSSH |)PRIVATE KEY/);
      expect(content).not.toMatch(/password\s*[:=]\s*['"]?[A-Za-z0-9_!@#$%^&*.-]{8,}/i);
    }
  });

  test("baseline template scans secrets and filesystem vulnerabilities", () => {
    const content = readTemplate("security-baseline.yml");

    expect(content).toContain("gitleaks/gitleaks-action@v2");
    expect(content).toContain("aquasecurity/trivy-action@0.24.0");
    expect(content).toContain("vuln,secret,misconfig");
  });

  test("web JS/TS production template includes SAST, SCA, filesystem scan, and staged DAST", () => {
    const content = readTemplate("security-production-web-js-ts.yml");

    expect(content).toContain("semgrep");
    expect(content).toContain("p/javascript");
    expect(content).toContain("p/typescript");
    expect(content).toContain("npm audit");
    expect(content).toContain("pnpm audit");
    expect(content).toContain("yarn npm audit");
    expect(content).toContain("aquasecurity/trivy-action@0.24.0");
    expect(content).toContain("secrets.STAGING_URL");
    expect(content).toContain("projectdiscovery/nuclei");
    expect(content).toContain("zap-baseline.py");
  });

  test("JS/TS production template does not include staging DAST", () => {
    const content = readTemplate("security-production-js-ts.yml");

    expect(content).toContain("semgrep");
    expect(content).toContain("p/typescript");
    expect(content).toContain("aquasecurity/trivy-action@0.24.0");
    expect(content).not.toContain("secrets.STAGING_URL");
    expect(content).not.toContain("zap-baseline.py");
  });
});
